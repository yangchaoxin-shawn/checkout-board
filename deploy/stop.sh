#!/bin/bash
set -eu
# ====================================================
# 每日作战打卡看板 — 停止脚本
# 用法：./deploy/stop.sh
# 说明：停止服务但不删除数据（./data/ 目录保留）
# ====================================================
set -e

cd "$(dirname "$0")/.."

echo "========================================"
echo "  每日作战打卡看板 — 停止"
echo "========================================"

echo "▶ 停止服务..."
docker compose down

echo ""
echo "  ✓ 服务已停止"
echo "  ✓ 数据保留在 ./data/ 目录中"
echo "  → 重新启动：./deploy/start.sh"
echo "========================================"
